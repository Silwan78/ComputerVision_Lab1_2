#importing needed libraries
import numpy as np
import matplotlib.pyplot as plt
from sklearn.datasets import make_blobs
from sklearn.cluster import KMeans
from skimage import data

#Dataset 1
#Step 1 – Generate the dataset
X, y_true = make_blobs(n_samples=1000, centers=4, random_state=42)

#Step 2 – Plot the dataset before applying K-Means
plt.figure(figsize=(8, 6))
plt.scatter(X[:, 0], X[:, 1], c="gray", s=20)
plt.title("Generated Data (1000 samples) - Before K-Means")
plt.xlabel("Feature 1")
plt.ylabel("Feature 2")
plt.savefig("kmeans_data_before.png")
plt.show()

#Step 3 – Apply K-Means
kmeans = KMeans(n_clusters=4, random_state=42)
labels = kmeans.fit_predict(X)

# Step 4 – Plot the dataset after applying K-Means
plt.figure(figsize=(8, 6))
plt.scatter(X[:, 0], X[:, 1], c=labels, cmap="viridis", s=20)
plt.scatter(
    kmeans.cluster_centers_[:, 0],
    kmeans.cluster_centers_[:, 1],
    c="red",
    marker="X",
    s=200,
    label="Cluster Centers",
)
plt.title("Generated Data (1000 samples) - After K-Means")
plt.xlabel("Feature 1")
plt.ylabel("Feature 2")
plt.legend()
plt.savefig("kmeans_data_after.png")
plt.show()

#Dataset 2
# Step 1 – Load the image
image = data.coffee()

# Step 2 – Show the image before applying K-Means
plt.figure(figsize=(8, 6))
plt.imshow(image)
plt.title("Original Image")
plt.axis("off")
plt.savefig("kmeans_image_before.png")
plt.show()

# Step 3 – Apply K-Means on the pixel colours
pixels = image.reshape(-1, 3)
kmeans_img = KMeans(n_clusters=4, random_state=42)
pixel_labels = kmeans_img.fit_predict(pixels)

# Step 4 – Show the image after applying K-Means
new_pixels = kmeans_img.cluster_centers_[pixel_labels]
segmented_image = new_pixels.reshape(image.shape).astype(np.uint8)

plt.figure(figsize=(8, 6))
plt.imshow(segmented_image)
plt.title("Image After K-Means (4 colours)")
plt.axis("off")
plt.savefig("kmeans_image_after.png")
plt.show()