import numpy as np
import matplotlib.pyplot as plt
from sklearn.datasets import make_circles
from sklearn.cluster import SpectralClustering
from sklearn.cluster import spectral_clustering
from sklearn.feature_extraction import image as sk_image
from skimage import data
from skimage.transform import rescale
from skimage.filters import gaussian

# Dataset 3: Concentric circles (Spectral Clustering)

# Step 1 – Generate the dataset
X_circles, y_circles = make_circles(n_samples=1000, factor=0.5, noise=0.05, random_state=42)

# Step 2 – Plot the dataset before applying Spectral Clustering
plt.figure(figsize=(8, 6))
plt.scatter(X_circles[:, 0], X_circles[:, 1], c="gray", s=20)
plt.title("Concentric Circles - Before Spectral Clustering")
plt.xlabel("Feature 1")
plt.ylabel("Feature 2")
plt.axis("equal")
plt.savefig("spectral_data_before.png")
plt.show()

# Step 3 – Apply Spectral Clustering
spectral = SpectralClustering(
    n_clusters=2,
    affinity="nearest_neighbors",
    random_state=42,
)
spectral_labels = spectral.fit_predict(X_circles)

# Step 4 – Plot the dataset after applying Spectral Clustering
plt.figure(figsize=(8, 6))
plt.scatter(X_circles[:, 0], X_circles[:, 1], c=spectral_labels, cmap="viridis", s=20)
plt.title("Concentric Circles - After Spectral Clustering")
plt.xlabel("Feature 1")
plt.ylabel("Feature 2")
plt.axis("equal")
plt.savefig("spectral_data_after.png")
plt.show()

# Dataset 4: Coins image (Spectral Clustering)
from skimage.filters import gaussian
from skimage.transform import rescale
from sklearn.feature_extraction.image import img_to_graph
from sklearn.cluster import spectral_clustering
# Step 1 – Load the image
coins = data.coins()

# Step 2 – Show the image before applying Spectral Clustering
plt.figure(figsize=(8, 6))
plt.imshow(coins, cmap="gray")
plt.title("Original Coins Image")
plt.axis("off")
plt.savefig("spectral_image_before.png")
plt.show()

# Step 3 – Apply Spectral Clustering
# Smooth and shrink the image so clustering runs faster
smoothed = gaussian(coins, sigma=2)
small = rescale(smoothed, 0.2, anti_aliasing=False)

# Build a graph of neighbouring pixels
graph = img_to_graph(small)

# Make pixels with similar brightness strongly connected
graph.data = np.exp(-10 * graph.data / graph.data.std())

# Cluster the graph
coin_labels = spectral_clustering(
    graph,
    n_clusters=25,
    assign_labels="discretize",
    random_state=42,
)
coin_labels = coin_labels.reshape(small.shape)

# Step 4 – Show the image after applying Spectral Clustering
plt.figure(figsize=(8, 6))
plt.imshow(coin_labels, cmap="nipy_spectral")
plt.title("Coins After Spectral Clustering (25 regions)")
plt.axis("off")
plt.savefig("spectral_image_after.png")
plt.show()